export function listWorkspaces(config) {
  const stored = readJson(workspacesPath(config), null);
  if (!Array.isArray(stored) || stored.length === 0) {
    const seeded = defaultWorkspaces();
    writeJson(workspacesPath(config), seeded);
    return seeded;
  }
  return stored.map((workspace) => ({
    ...workspace,
    params: normalizeParams(workspace.params),
    tools: Array.isArray(workspace.tools) ? workspace.tools : [],
    retrieval: { enabled: true, topK: 4, ...(workspace.retrieval ?? {}) },
  }));
}

export function getWorkspace(config, workspaceId) {
  const workspaces = listWorkspaces(config);
  return workspaces.find((workspace) => workspace.id === workspaceId) ?? workspaces[0];
}

export function saveWorkspace(config, patch) {
  const workspaces = listWorkspaces(config);
  const now = new Date().toISOString();
  const index = workspaces.findIndex((workspace) => workspace.id === patch.id);
  if (index === -1) {
    const created = {
      id: newId("ws-"),
      name: String(patch.name ?? "Untitled workspace").slice(0, 48),
      description: String(patch.description ?? "").slice(0, 160),
      icon: String(patch.icon ?? "◆").slice(0, 2),
      systemPrompt: String(patch.systemPrompt ?? DEFAULT_SYSTEM_PROMPT),
      params: normalizeParams(patch.params),
      tools: Array.isArray(patch.tools) ? patch.tools : [],
      retrieval: { enabled: true, topK: 4, ...(patch.retrieval ?? {}) },
      createdAt: now,
      updatedAt: now,
      builtIn: false,
    };
    workspaces.push(created);
    writeJson(workspacesPath(config), workspaces);
    return created;
  }
  const updated = {
    ...workspaces[index],
    ...patch,
    params: normalizeParams(patch.params ?? workspaces[index].params),
    tools: Array.isArray(patch.tools) ? patch.tools : workspaces[index].tools,
    retrieval: { ...workspaces[index].retrieval, ...(patch.retrieval ?? {}) },
    id: workspaces[index].id,
    builtIn: workspaces[index].builtIn,
    createdAt: workspaces[index].createdAt,
    updatedAt: now,
  };
  workspaces[index] = updated;
  writeJson(workspacesPath(config), workspaces);
  return updated;
}

export function deleteWorkspace(config, workspaceId) {
  const workspaces = listWorkspaces(config);
  const target = workspaces.find((workspace) => workspace.id === workspaceId);
  if (!target) {
    throw new Error("Workspace not found.");
  }
  if (target.builtIn) {
    throw new Error("Built-in workspaces cannot be deleted. Edit it instead.");
  }
  const remaining = workspaces.filter((workspace) => workspace.id !== workspaceId);
  writeJson(workspacesPath(config), remaining);
  // Conversations that belonged to it move to the first workspace rather than
  // disappearing - deleting a container should never delete transcripts.
  for (const summary of listConversations(config)) {
    if (summary.workspaceId === workspaceId) {
      const conversation = getConversation(config, summary.id);
      if (conversation) {
        conversation.workspaceId = remaining[0].id;
        writeConversation(config, conversation);
      }
    }
  }
  return { ok: true, movedTo: remaining[0].id };
}

// ---- Conversations --------------------------------------------------------

export function createConversation(config, { workspaceId, title } = {}) {
  const workspace = getWorkspace(config, workspaceId);
  const now = new Date().toISOString();
  const conversation = {
    id: newId("c-"),
    workspaceId: workspace.id,
    title: title ? String(title).slice(0, CONVERSATION_TITLE_MAX) : "New chat",
    titleLocked: Boolean(title),
    pinned: false,
    createdAt: now,
    updatedAt: now,
    messages: [],
  };
  writeConversation(config, conversation);
  return conversation;
}

export function getConversation(config, id) {
  const conversation = readJson(conversationPath(config, id), null);
  if (!conversation) {
    return null;
  }
  conversation.messages = Array.isArray(conversation.messages) ? conversation.messages : [];
  return conversation;
}

export function writeConversation(config, conversation) {
  conversation.updatedAt = new Date().toISOString();
  writeJson(conversationPath(config, conversation.id), conversation);
  return conversation;
}

// Sidebar projection: metadata plus a one-line preview, never full transcripts.
export function listConversations(config) {
  const directory = conversationsDirectory(config);
  if (!fs.existsSync(directory)) {
    return [];
  }
  const summaries = [];
  for (const entry of fs.readdirSync(directory)) {
    if (!entry.endsWith(".json")) continue;
    const conversation = readJson(path.join(directory, entry), null);
    if (!conversation?.id) continue;
    const last = [...(conversation.messages ?? [])].reverse()
      .find((message) => message.role === "user" || message.role === "assistant");
    summaries.push({
      id: conversation.id,
      workspaceId: conversation.workspaceId,
      title: conversation.title ?? "New chat",
      pinned: Boolean(conversation.pinned),
      createdAt: conversation.createdAt,
      updatedAt: conversation.updatedAt,
      messageCount: (conversation.messages ?? []).length,
      preview: last ? String(last.content ?? "").replace(/\s+/g, " ").slice(0, 120) : "",
    });
  }
  summaries.sort((a, b) => {
    if (a.pinned !== b.pinned) return a.pinned ? -1 : 1;
    return String(b.updatedAt).localeCompare(String(a.updatedAt));
  });
  return summaries;
}

export function deleteConversation(config, id) {
  const filePath = conversationPath(config, id);
  if (fs.existsSync(filePath)) {
    fs.unlinkSync(filePath);
  }
  return { ok: true };
}

export function appendMessage(config, conversationId, message) {
  const conversation = getConversation(config, conversationId);
  if (!conversation) {
    throw new Error("Conversation not found.");
  }
  const entry = {
    id: newId("m-"),
    role: message.role,
    content: String(message.content ?? ""),
    createdAt: new Date().toISOString(),
    ...(message.reasoning ? { reasoning: message.reasoning } : {}),
    ...(message.stats ? { stats: message.stats } : {}),
    ...(message.citations ? { citations: message.citations } : {}),
    ...(message.toolCalls ? { toolCalls: message.toolCalls } : {}),
    ...(message.attachments ? { attachments: message.attachments } : {}),
    // A validated chart spec (src/lib/chat/chart-agent.js). Stored with the
    // message so reopening the conversation redraws the chart rather than
    // leaving an answer that refers to a picture which is no longer there.
    ...(message.chart ? { chart: message.chart } : {}),
  };
  conversation.messages.push(entry);
  // The first user message names the chat, the way a subject line names a
  // thread. An explicit rename locks it so it never gets overwritten.
  if (!conversation.titleLocked && entry.role === "user" && conversation.title === "New chat") {
    conversation.title = deriveTitle(entry.content);
  }
  writeConversation(config, conversation);
  return entry;
}

export function deriveTitle(text) {
  const flat = String(text ?? "").replace(/\s+/g, " ").trim();
  if (!flat) {
    return "New chat";
  }
  if (flat.length <= CONVERSATION_TITLE_MAX) {
    return flat;
  }
  return `${flat.slice(0, CONVERSATION_TITLE_MAX - 1).trimEnd()}…`;
}

export function updateConversation(config, id, patch) {
  const conversation = getConversation(config, id);
  if (!conversation) {
    throw new Error("Conversation not found.");
  }
  if (typeof patch.title === "string" && patch.title.trim()) {
    conversation.title = patch.title.trim().slice(0, CONVERSATION_TITLE_MAX);
    conversation.titleLocked = true;
  }
  if (typeof patch.pinned === "boolean") {
    conversation.pinned = patch.pinned;
  }
  if (typeof patch.workspaceId === "string") {
    conversation.workspaceId = getWorkspace(config, patch.workspaceId).id;
  }
  return writeConversation(config, conversation);
}

// Truncates the transcript at (and including) a message - the primitive behind
// "edit and resend" and "regenerate", which both mean "rewind to here".
export function truncateFrom(config, conversationId, messageId, { inclusive = true } = {}) {
  const conversation = getConversation(config, conversationId);
  if (!conversation) {
    throw new Error("Conversation not found.");
  }
  const index = conversation.messages.findIndex((message) => message.id === messageId);
  if (index === -1) {
    return conversation;
  }
  conversation.messages = conversation.messages.slice(0, inclusive ? index : index + 1);
  return writeConversation(config, conversation);
}

// Prior turns the model should see, oldest first, bounded by the workspace's
// historyTurns setting. Tool transcripts stay out: they are re-derived per turn.
export function recentTurns(conversation, historyTurns) {
  const turns = (conversation.messages ?? []).filter(
    (message) => message.role === "user" || message.role === "assistant",
  );
  if (historyTurns <= 0) {
    return [];
  }
  return turns.slice(-historyTurns * 2);
}

export function exportConversationMarkdown(conversation, workspace) {
  const lines = [
    `# ${conversation.title}`,
    "",
    `- Workspace: ${workspace?.name ?? "—"}`,
    `- Started: ${conversation.createdAt}`,
    `- Messages: ${conversation.messages.length}`,
    "",
    "---",
    "",
  ];
  for (const message of conversation.messages) {
    if (message.role === "user") {
      lines.push(`## You`, "", message.content, "");
    } else if (message.role === "assistant") {
      const stamp = message.stats?.tokensPerSecond
        ? ` _(${message.stats.tokensPerSecond.toFixed(1)} tok/s · ${message.stats.runtimeProvider ?? "local"})_`
        : "";
      lines.push(`## Lizard${stamp}`, "", message.content, "");
      if (message.citations?.length) {
        lines.push("Sources:", "");
        message.citations.forEach((citation, position) => {
          lines.push(`${position + 1}. ${citation.documentName}${citation.locator ? ` — ${citation.locator}` : ""}`);
        });
        lines.push("");
      }
    }
  }
  return lines.join("\n");
}
