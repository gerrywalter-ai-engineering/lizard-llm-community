// Persistent chat state for the Lizard Chat workspace.
//
// Two levels, mirroring how people actually work:
//   workspace    a named context - system prompt, generation params, its own
//                documents and enabled tools. Conversations live inside one.
//   conversation an ordered message list plus the metadata the sidebar needs.
//
// Everything is plain JSON under <runtimeDirectory>/chat so a user can back it
// up, inspect it, or delete it with a file manager. Nothing leaves the machine.
//
// The model is deliberately NOT stored per workspace: Lizard binds chat to the
// one activated model (see resolveBoundModel in src/ui/chat-routes.js), and the
// only place that binding changes is onboarding's Activate step.

import fs from "node:fs";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { ensureDirectory } from "../paths.js";

const CONVERSATION_TITLE_MAX = 60;

export const DEFAULT_PARAMS = Object.freeze({
  temperature: 0.7,
  topP: 0.9,
  maxTokens: 512,
  historyTurns: 12,
});

export const DEFAULT_SYSTEM_PROMPT =
  "You are Lizard, a helpful assistant running entirely on this machine. " +
  "Answer directly and concretely. Use Markdown for structure and fenced code " +
  "blocks with a language tag for code.";

function chatRoot(config) {
  return path.join(config?.runtimeDirectory ?? process.cwd(), "chat");
}

function workspacesPath(config) {
  return path.join(chatRoot(config), "workspaces.json");
}

function conversationsDirectory(config) {
  return path.join(chatRoot(config), "conversations");
}

function conversationPath(config, id) {
  return path.join(conversationsDirectory(config), `${safeId(id)}.json`);
}

// Ids are generated by us, but they also arrive from HTTP requests. A hostile
// id is rejected rather than scrubbed: silently rewriting "../../secrets" into
// a valid-looking id would hand back somebody else's file instead of an error.
export function safeId(value) {
  const raw = String(value ?? "");
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(raw)) {
    throw new Error("Invalid id.");
  }
  return raw;
}

function readJson(filePath, fallback) {
  try {
    if (!fs.existsSync(filePath)) {
      return fallback;
    }
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch {
    return fallback;
  }
}

function writeJson(filePath, value) {
  ensureDirectory(path.dirname(filePath));
  // Write-then-rename so a crash mid-write cannot leave a truncated
  // conversation behind - the sidebar reads these files on every load.
  const temporary = `${filePath}.tmp`;
  fs.writeFileSync(temporary, JSON.stringify(value, null, 2));
  fs.renameSync(temporary, filePath);
}

export function newId(prefix) {
  const uuid = typeof randomUUID === "function"
    ? randomUUID().replace(/-/g, "").slice(0, 20)
    : `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 10)}`;
  return `${prefix}${uuid}`;
}

function normalizeParams(params) {
  const merged = { ...DEFAULT_PARAMS, ...(params ?? {}) };
  return {
    temperature: clamp(Number(merged.temperature), 0, 2, DEFAULT_PARAMS.temperature),
    topP: clamp(Number(merged.topP), 0.01, 1, DEFAULT_PARAMS.topP),
    maxTokens: Math.round(clamp(Number(merged.maxTokens), 32, 4096, DEFAULT_PARAMS.maxTokens)),
    historyTurns: Math.round(clamp(Number(merged.historyTurns), 0, 40, DEFAULT_PARAMS.historyTurns)),
  };
}

function clamp(value, min, max, fallback) {
  if (!Number.isFinite(value)) {
    return fallback;
  }
  return Math.min(max, Math.max(min, value));
}

